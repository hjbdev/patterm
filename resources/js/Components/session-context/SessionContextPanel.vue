<template>
  <div class="flex min-h-0 flex-1 flex-col">
    <header class="flex h-11 shrink-0 items-center gap-2 pl-4 pr-2.5">
      <h2 class="min-w-0 flex-1 truncate text-[13px] font-medium">Session context</h2>
      <Button variant="ghost" size="icon" class="h-7 w-7 text-muted-foreground hover:text-foreground" aria-label="Close session context" @click="emit('close')"><X class="h-4 w-4" /></Button>
    </header>
    <div class="min-h-0 flex-1 overflow-y-auto overscroll-contain px-4 pb-6">
      <section v-if="summary" class="pb-6 pt-0.5">
        <p class="whitespace-pre-wrap break-words text-[13px] leading-[1.6] text-foreground/90">{{ summary.text }}</p>
        <p class="mt-2 text-[11px] text-muted-foreground/70" :title="`Generated by ${summary.model} on ${new Date(summary.generatedAt).toLocaleString()}`">Updated {{ relativeTime(summary.generatedAt, now) }}</p>
      </section>

      <div class="space-y-4">
        <section aria-labelledby="context-worktrees">
          <div class="flex h-7 items-center gap-2">
            <h3 id="context-worktrees" class="text-xs font-medium" :class="heading(worktrees.length)">Worktrees</h3>
            <span v-if="worktrees.length" class="text-[11px] tabular-nums text-muted-foreground/50">{{ worktrees.length }}</span>
            <ContextPicker :items="worktreeOptions" placeholder="Search worktrees…" label="Search worktrees to link" empty-text="This project has no worktrees." :disabled="busy" @select="linkWorktree">
              <Button variant="ghost" size="icon" :class="ADD" :disabled="busy || linkedWorktrees >= MAX_LINKED_WORKTREES" aria-label="Link a project worktree" title="Link a project worktree"><Plus class="h-3.5 w-3.5" /></Button>
            </ContextPicker>
          </div>
          <div class="-mx-2">
            <ContextWorktreeRow v-for="worktree in worktrees" :key="worktree.id" :worktree="worktree" :state="diffTotals.get(worktree.id)" :active="worktree.id === activeWorktreeId" :busy="busy" @open="emit('openWorktree', worktree)" @unlink="unlinkWorktree(worktree.id)" />
          </div>
        </section>

        <section aria-labelledby="context-todos">
          <div class="flex h-7 items-center gap-2">
            <h3 id="context-todos" class="text-xs font-medium" :class="heading(todos.length)">Todos</h3>
            <span v-if="todos.length" class="text-[11px] tabular-nums text-muted-foreground/50">{{ todos.length }}</span>
            <ContextPicker v-model:query="todoQuery" :items="todoOptions" placeholder="Search or create a todo…" label="Search todos to assign" empty-text="No todos found." create-label="New todo" :disabled="busy" @select="assignTodo" @create="createTodo">
              <Button variant="ghost" size="icon" :class="ADD" :disabled="busy" aria-label="Add a todo" title="Add a todo"><Plus class="h-3.5 w-3.5" /></Button>
            </ContextPicker>
          </div>
          <div class="-mx-2">
            <ContextTodoRow v-for="todo in todos" :key="todo.id" :todo="todo" :project-id="projectId" :now="now" :busy="busy" @status="setTodoStatus(todo, $event)" @unassign="unassignTodo(todo.id)" />
          </div>
        </section>

        <section aria-labelledby="context-scratchpads">
          <div class="flex h-7 items-center gap-2">
            <h3 id="context-scratchpads" class="text-xs font-medium" :class="heading(scratchpads.length)">Scratchpads</h3>
            <span v-if="scratchpads.length" class="text-[11px] tabular-nums text-muted-foreground/50">{{ scratchpads.length }}</span>
            <ContextPicker v-model:query="noteQuery" :items="noteOptions" placeholder="Search or create a scratchpad…" label="Search scratchpads to attach" empty-text="No scratchpads found." create-label="New scratchpad" :disabled="busy" @select="attachScratchpad" @create="createScratchpad">
              <Button variant="ghost" size="icon" :class="ADD" :disabled="busy" aria-label="Add a scratchpad" title="Add a scratchpad"><Plus class="h-3.5 w-3.5" /></Button>
            </ContextPicker>
          </div>
          <div class="-mx-2">
            <ContextScratchpadRow v-for="note in scratchpads" :key="note.id" :note="note" :project-id="projectId" :busy="busy" @detach="detachScratchpad(note.id)" />
          </div>
        </section>

        <section aria-labelledby="context-links">
          <div class="flex h-7 items-center gap-2">
            <h3 id="context-links" class="text-xs font-medium" :class="heading(links.length)">Links</h3>
            <span v-if="links.length" class="text-[11px] tabular-nums text-muted-foreground/50">{{ links.length }}</span>
            <LinkAttachPopover :busy="busy" @attach="(url, done) => attachLink(url).then(done)">
              <Button variant="ghost" size="icon" :class="ADD" :disabled="busy" aria-label="Add a link" title="Add a link"><Plus class="h-3.5 w-3.5" /></Button>
            </LinkAttachPopover>
          </div>
          <div class="-mx-2">
            <ContextLinkRow v-for="link in links" :key="link.id" :link="link" :busy="busy" @update="(changes, done) => updateLink(link, changes).then(done)" @detach="detachLink(link.id)" />
          </div>
        </section>

        <!-- A paired host's history stays on that host. -->
        <ContextMedia v-if="!sessionId.includes(':')" :project-id="projectId" :session-id="sessionId" />
      </div>

      <p v-if="truncated" class="mt-5 text-[11px] text-muted-foreground">Showing the first 100 items. Open the project views for more.</p>
      <p v-if="error" role="alert" class="mt-3 text-xs text-destructive">{{ error }}</p>
    </div>
    <CreateContextItemDialog v-model:open="todoDialogOpen" kind="todo" :project-id="projectId" :session-id="sessionId" :initial-title="draftTitle" @created="refresh" />
    <CreateContextItemDialog v-model:open="noteDialogOpen" kind="scratchpad" :project-id="projectId" :session-id="sessionId" :initial-title="draftTitle" @created="refresh" />
  </div>
</template>

<script setup lang="ts">
import { ref } from 'vue';
import { Plus, X } from 'lucide-vue-next';
import CreateContextItemDialog from '../CreateContextItemDialog.vue';
import { Button } from '../ui/button';
import ContextLinkRow from './ContextLinkRow.vue';
import ContextMedia from './ContextMedia.vue';
import ContextPicker from './ContextPicker.vue';
import ContextScratchpadRow from './ContextScratchpadRow.vue';
import ContextTodoRow from './ContextTodoRow.vue';
import ContextWorktreeRow from './ContextWorktreeRow.vue';
import LinkAttachPopover from './LinkAttachPopover.vue';
import { MAX_LINKED_WORKTREES, useSessionContext } from '../../Composables/useSessionContext';
import { relativeTime } from '../../lib/format';
import type { SessionWorktree } from '../../lib/projectContext';
import type { AutoSummaryRecord } from '../../types';

// Flat sections with counts, one add picker per section, and row
// actions that appear on hover.
const props = defineProps<{ projectId: string; sessionId: string; summary?: AutoSummaryRecord | null | undefined; activeWorktreeId?: string | null | undefined }>();
const emit = defineEmits<{ openWorktree: [worktree: SessionWorktree]; close: [] }>();
const { now, todos, scratchpads, links, worktrees, linkedWorktrees, worktreeOptions, todoOptions, noteOptions, todoQuery, noteQuery, diffTotals, truncated, error, busy, refresh,
  linkWorktree, unlinkWorktree, assignTodo, unassignTodo, setTodoStatus, attachScratchpad, detachScratchpad, attachLink, updateLink, detachLink } = useSessionContext(props);
const todoDialogOpen = ref(false), noteDialogOpen = ref(false), draftTitle = ref('');
// The negative margin lines the add buttons up with the row actions below them.
const ADD = '-mr-1 ml-auto h-6 w-6 text-muted-foreground/70 hover:text-foreground';
// Empty sections recede so the ones in use stand out.
const heading = (count: number) => (count ? 'text-muted-foreground' : 'text-muted-foreground/60');

function createTodo(title: string) {
  draftTitle.value = title;
  todoDialogOpen.value = true;
}
function createScratchpad(title: string) {
  draftTitle.value = title;
  noteDialogOpen.value = true;
}
</script>
