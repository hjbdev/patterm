<template>
  <!-- The agent's context in the conversation: its name, the goal from its
       summary, then a chip for each kind of thing attached to it, in a fixed
       order so their places become familiar. Empty kinds don't show; + adds
       one. A chip opens its list, as a sheet on a phone. -->
  <!-- No rule below it: a conversation fades in under it instead. -->
  <header class="relative z-10 shrink-0 bg-background" :class="phoneLayout ? (folded ? '' : 'pb-2.5') : 'pb-3 pt-4'">
    <div class="mx-auto w-full" :class="phoneLayout ? '' : ['px-4', inner]">
      <div class="flex items-center gap-1" :class="phoneLayout ? 'h-12 pl-1 pr-1.5' : ''">
        <slot name="leading" />
        <SidebarItemMenu :session="session" :tab="menuTab">
          <h1 class="min-w-0 flex-1 select-none truncate font-medium [-webkit-touch-callout:none]" :class="phoneLayout ? 'text-[15px]' : 'text-[14.5px]'">
            {{ agentLabel(session) }}<HostBadge v-if="session.host" :host="session.host" class="ml-1.5" />
          </h1>
        </SidebarItemMenu>
        <slot name="trailing" />
      </div>
      <div v-if="summary && goal && !folded && !phoneLayout" class="mt-1 text-[12.5px] leading-5 text-muted-foreground">
        <button type="button" class="group/goal flex max-w-full items-start gap-1 rounded-sm text-left transition-colors hover:text-foreground/85 focus-visible:outline-none focus-visible:ring-1 focus-visible:ring-ring" :aria-expanded="goalOpen" @click="goalOpen = !goalOpen">
          <span v-if="goalOpen" class="min-w-0 whitespace-pre-wrap break-words text-foreground/85">{{ summary.text }}</span>
          <span v-else class="min-w-0 truncate">{{ goal }}</span>
          <ChevronDown class="mt-[3px] h-3.5 w-3.5 shrink-0 opacity-50 transition-[transform,opacity] group-hover/goal:opacity-100" :class="goalOpen && 'rotate-180'" aria-hidden="true" />
        </button>
        <p v-if="goalOpen" class="mt-0.5 flex items-center gap-1.5 text-[11.5px]">
          <span :title="`Generated by ${summary.model} on ${new Date(summary.generatedAt).toLocaleString()}`">Updated {{ relativeTime(summary.generatedAt, now) }}</span>
          <AutoSummaryControls v-if="canSummarize" :key="session.id" :project-id="projectId" :session-id="session.id" class="-my-1" />
        </p>
      </div>
      <!-- Folding hides the chips without unmounting them, so an open chip's
           form survives the phone keyboard that typing in it brings up, and
           a new secret request still opens its list. -->
      <div v-show="!folded || openChip" class="flex items-center gap-1.5" :class="phoneLayout ? 'mt-1.5 overflow-x-auto px-3 [scrollbar-width:none]' : 'mt-2.5 flex-wrap'">
        <ResponsivePopover v-if="worktrees.length" v-bind="chip('worktrees')" title="Worktrees" content-class="w-[22rem]">
          <template #trigger><button type="button" :class="CHIP"><FolderGit2 :class="CHIP_ICON" /><span :class="CHIP_LABEL">{{ counted(worktrees.length, 'worktree', 'worktrees') }}</span></button></template>
          <ContextWorktreeRow v-for="worktree in worktrees" :key="worktree.id" dense :worktree="worktree" :state="diffTotals.get(worktree.id)" :active="worktree.id === activeWorktreeId" :busy="busy" @open="openDiff(worktree)" @unlink="unlinkWorktree(worktree.id)" />
          <div :class="SEPARATOR" />
          <ContextPicker :items="worktreeOptions" placeholder="Search worktrees…" label="Search worktrees to link" empty-text="This project has no worktrees." align="start" :disabled="busy || linkedWorktrees >= MAX_LINKED_WORKTREES" @select="linkWorktree">
            <button type="button" :class="ADD_ROW"><Plus :class="CHIP_ICON" />Link a worktree</button>
          </ContextPicker>
        </ResponsivePopover>

        <ResponsivePopover v-if="pages.length" v-bind="chip('links')" title="Links">
          <template #trigger><button type="button" :class="CHIP"><component :is="pages.length === 1 ? linkIcon(pages[0]!) : Link2" :class="CHIP_ICON" /><span :class="[CHIP_LABEL, 'max-w-48 truncate']">{{ pages.length === 1 ? linkLabel(pages[0]!) : `${pages.length} links` }}</span></button></template>
          <ContextLinkRow v-for="link in pages" :key="link.id" dense :link="link" :busy="busy" @update="(changes, done) => updateLink(link, changes).then(done)" @detach="detachLink(link.id)" />
          <div :class="SEPARATOR" />
          <LinkAttachPopover :busy="busy" align="start" @attach="(url, done) => attachLink(url).then(done)">
            <button type="button" :class="ADD_ROW"><Plus :class="CHIP_ICON" />Add a link</button>
          </LinkAttachPopover>
        </ResponsivePopover>

        <!-- The agent's own browser, once it has one. It opens beside the
             conversation. -->
        <button v-if="browser?.running" type="button" :class="CHIP" @click="emit('peek', { kind: 'browser' })"><Globe :class="CHIP_ICON" /><span :class="CHIP_LABEL">Browser</span><span v-if="browser.help" class="h-1.5 w-1.5 rounded-full bg-foreground" aria-label="needs you" /></button>

        <!-- Secrets the agent asked for or was given. A new request opens the
             list, where its form waits. They stay on the agent's own host. -->
        <SecretsChip v-if="hasSecrets(session.processId)" v-bind="chip('secrets')" :process-id="session.processId" />

        <!-- Servers the agent started, and preview links. One with a page opens
             it in the agent's browser beside the conversation. -->
        <ResponsivePopover v-if="servers.length" v-bind="chip('servers')" :title="serversLabel">
          <template #trigger><button type="button" :class="CHIP"><MonitorPlay :class="CHIP_ICON" /><span :class="[CHIP_LABEL, 'max-w-48 truncate']">{{ serversLabel }}</span></button></template>
          <div v-for="server in servers" :key="server.key" class="group/row flex items-center rounded-md pr-1 transition-colors hover:bg-muted/40">
            <button type="button" :class="[ROW, 'relative isolate hover:bg-transparent']" @click="openServer(server)">
              <RowStatus v-if="server.process" :activity="processActivity(server.process)" />
              <AppWindow v-else :class="CHIP_ICON" />
              <span class="min-w-0 truncate">{{ server.label }}</span>
              <span v-if="server.port" class="shrink-0 font-mono text-xs text-muted-foreground">:{{ server.port }}</span>
            </button>
            <button v-if="server.process && server.url" type="button" :class="ROW_ACTION" :aria-label="`Show ${server.label}'s terminal`" title="Show terminal" @click="openProcess(server.process)"><SquareTerminal class="h-3.5 w-3.5" /></button>
            <a v-if="server.url" :href="server.url" target="_blank" rel="noopener noreferrer" :class="ROW_ACTION" :aria-label="`Open ${server.label} in the browser`" title="Open in browser"><ExternalLink class="h-3.5 w-3.5" /></a>
          </div>
        </ResponsivePopover>

        <!-- The rest of the agent's family, whether or not the sidebar lists them. -->
        <ResponsivePopover v-if="agents.length" v-bind="chip('agents')" :title="agentsLabel">
          <template #trigger><button type="button" :class="CHIP"><Network :class="CHIP_ICON" /><span :class="CHIP_LABEL">{{ agentsLabel }}</span></button></template>
          <button v-for="member in agents" :key="member.id" type="button" :class="[ROW, 'relative isolate']" @click="openAgent(member)">
            <RowStatus :activity="sidebar.activity(member)" />
            <span class="min-w-0 flex-1 truncate">{{ agentLabel(member) }}</span>
            <HostBadge v-if="member.host" :host="member.host" />
          </button>
        </ResponsivePopover>

        <ResponsivePopover v-if="openTodos" v-bind="chip('todos')" title="Todos" content-class="w-[22rem]">
          <template #trigger><button type="button" :class="CHIP"><ListTodo :class="CHIP_ICON" /><span :class="CHIP_LABEL">{{ counted(openTodos, 'todo', 'todos') }}</span></button></template>
          <ContextTodoRow v-for="todo in todos" :key="todo.id" dense :todo="todo" :project-id="projectId" :now="now" :busy="busy" @status="setTodoStatus(todo, $event)" @unassign="unassignTodo(todo.id)" />
        </ResponsivePopover>

        <ResponsivePopover v-if="scratchpads.length" v-bind="chip('scratchpads')" title="Scratchpads">
          <template #trigger><button type="button" :class="CHIP"><NotebookPen :class="CHIP_ICON" /><span :class="CHIP_LABEL">{{ counted(scratchpads.length, 'scratchpad', 'scratchpads') }}</span></button></template>
          <ContextScratchpadRow v-for="note in scratchpads" :key="note.id" dense :note="note" :project-id="projectId" :busy="busy" @detach="detachScratchpad(note.id)" />
        </ResponsivePopover>

        <ResponsivePopover v-if="mediaTotal" v-bind="chip('media')" title="Media" content-class="w-72">
          <template #trigger><button type="button" :class="CHIP" :aria-label="counted(mediaTotal, 'image', 'images')"><Images :class="CHIP_ICON" />{{ mediaTotal }}</button></template>
          <div class="grid grid-cols-4 gap-1.5 p-1">
            <MediaThumb v-for="(image, index) in gallery" :key="image.key" :image="image" :project-id="projectId" @open="openImage(index)" />
          </div>
          <RouterLink :to="{ name: 'media', params: { projectId }, query: { session: session.id } }" :class="ADD_ROW" @click="openChip = null">Show all {{ mediaTotal }}</RouterLink>
        </ResponsivePopover>

        <ResponsivePopover v-bind="chip('add')" title="Add to this agent" content-class="w-56">
          <template #trigger>
            <button type="button" :class="ADD_CHIP" aria-label="Add a worktree, todo, scratchpad or link" title="Add a worktree, todo, scratchpad or link"><Plus class="h-4 w-4" /></button>
          </template>
          <ContextPicker :items="worktreeOptions" placeholder="Search worktrees…" label="Search worktrees to link" empty-text="This project has no worktrees." align="start" :disabled="busy || linkedWorktrees >= MAX_LINKED_WORKTREES" @select="linkWorktree">
            <button type="button" :class="ROW"><FolderGit2 :class="CHIP_ICON" />Worktree</button>
          </ContextPicker>
          <ContextPicker v-model:open="todoPickerOpen" v-model:query="todoQuery" :items="todoOptions" placeholder="Search or create a todo…" label="Search todos to assign" :empty-text="todoPickerLoaded ? 'No todos found.' : 'Loading…'" create-label="New todo" align="start" :disabled="busy" @select="assignTodo" @create="createTodo">
            <button type="button" :class="ROW"><ListTodo :class="CHIP_ICON" />Todo</button>
          </ContextPicker>
          <ContextPicker v-model:open="notePickerOpen" v-model:query="noteQuery" :items="noteOptions" placeholder="Search or create a scratchpad…" label="Search scratchpads to attach" :empty-text="notePickerLoaded ? 'No scratchpads found.' : 'Loading…'" create-label="New scratchpad" align="start" :disabled="busy" @select="attachScratchpad" @create="createScratchpad">
            <button type="button" :class="ROW"><NotebookPen :class="CHIP_ICON" />Scratchpad</button>
          </ContextPicker>
          <LinkAttachPopover :busy="busy" align="start" @attach="(url, done) => attachLink(url).then(done)">
            <button type="button" :class="ROW"><Link2 :class="CHIP_ICON" />Link</button>
          </LinkAttachPopover>
        </ResponsivePopover>
      </div>
      <p v-if="error" role="alert" class="mt-2 text-xs text-destructive" :class="phoneLayout && 'px-3'">{{ error }}</p>
    </div>
    <CreateContextItemDialog v-model:open="todoDialogOpen" kind="todo" :project-id="projectId" :session-id="session.id" :initial-title="draftTitle" @created="refresh" />
    <CreateContextItemDialog v-model:open="noteDialogOpen" kind="scratchpad" :project-id="projectId" :session-id="session.id" :initial-title="draftTitle" @created="refresh" />
  </header>
</template>

<script setup lang="ts">
import { computed, ref, watch } from 'vue';
import { RouterLink } from 'vue-router';
import { cn } from '@/lib/utils';
import { AppWindow, ChevronDown, ExternalLink, FolderGit2, Globe, Images, Link2, ListTodo, MonitorPlay, Network, NotebookPen, Plus, SquareTerminal } from 'lucide-vue-next';
import AutoSummaryControls from '../AutoSummaryControls.vue';
import CreateContextItemDialog from '../CreateContextItemDialog.vue';
import HostBadge from '../HostBadge.vue';
import ResponsivePopover from '../ResponsivePopover.vue';
import RowStatus from '../RowStatus.vue';
import MediaThumb from '../peek/MediaThumb.vue';
import SidebarItemMenu from '../Sidebar/SidebarItemMenu.vue';
import { familyTabOf, useSidebar } from '../Sidebar/sidebarContext';
import ContextLinkRow from './ContextLinkRow.vue';
import ContextPicker from './ContextPicker.vue';
import ContextScratchpadRow from './ContextScratchpadRow.vue';
import ContextTodoRow from './ContextTodoRow.vue';
import ContextWorktreeRow from './ContextWorktreeRow.vue';
import LinkAttachPopover from './LinkAttachPopover.vue';
import { CHIP, CHIP_ICON, CHIP_LABEL } from './rowAction';
import SecretsChip from './SecretsChip.vue';
import { useMedia } from '../../Composables/useMedia';
import { linkIcon, linkLabel, MAX_LINKED_WORKTREES, useSessionContext } from '../../Composables/useSessionContext';
import { agentLabel } from '../../lib/agentTabs';
import { hasBrowser, useBrowserState } from '../../lib/browser';
import { relativeTime } from '../../lib/format';
import type { Peek } from '../../lib/peek';
import { phoneLayout } from '../../lib/phoneLayout';
import type { SessionWorktree } from '../../lib/projectContext';
import { processActivity } from '../../lib/rowActivity';
import { hasSecrets } from '../../lib/secrets';
import { familyServers } from '../../lib/servers';
import type { ProcessRecord, SessionRecord } from '../../types';

// `inner` lines the header up with what's below it, such as the conversation
// column. Folded, only the name shows, as over a terminal while typing.
const props = defineProps<{ projectId: string; session: SessionRecord; inner?: string | undefined; activeWorktreeId?: string | null | undefined; folded?: boolean | undefined }>();
const emit = defineEmits<{ peek: [peek: Peek] }>();
const sidebar = useSidebar();

const ADD_CHIP = cn(CHIP, 'w-7 justify-center px-0 max-sm:w-8 max-sm:px-0');
const ROW = 'flex min-h-8 w-full min-w-0 flex-1 items-center gap-2.5 rounded-md px-2 py-1 text-left text-[13px] outline-none transition-colors hover:bg-muted/40 focus-visible:ring-1 focus-visible:ring-ring max-sm:min-h-11 max-sm:text-sm';
const ADD_ROW = `${ROW} text-muted-foreground hover:text-foreground`;
const ROW_ACTION = 'flex h-6 w-6 shrink-0 items-center justify-center rounded text-muted-foreground opacity-0 transition-opacity hover:text-foreground focus-visible:opacity-100 group-hover/row:opacity-100 [@media(hover:none)]:opacity-100';
const SEPARATOR = 'mx-2 my-1 h-px bg-white/[0.07]';

// One chip's list open at a time.
const openChip = ref<string | null>(null);
const sessionProps = { get projectId() { return props.projectId; }, get sessionId() { return props.session.id; } };
const { now, todos, scratchpads, links, worktrees, linkedWorktrees, worktreeOptions, todoOptions, noteOptions, todoQuery, noteQuery, todoPickerOpen, notePickerOpen, todoPickerLoaded, notePickerLoaded, diffTotals, error, busy, refresh,
  linkWorktree, unlinkWorktree, assignTodo, unassignTodo, setTodoStatus, attachScratchpad, detachScratchpad, attachLink, updateLink, detachLink } = useSessionContext(sessionProps, { diffTotals: computed(() => openChip.value === 'worktrees') });
const pages = computed(() => links.value.filter((link) => link.resource_type !== 'preview'));
const openTodos = computed(() => todos.value.filter((todo) => todo.status !== 'completed').length);
const browser = useBrowserState(() => props.session.processId);

// A paired host's media stays on that host.
const media = useMedia(sessionProps, { pageSize: 8, enabled: () => !props.session.id.includes(':') });
const mediaTotal = media.total;
const gallery = media.gallery;

// One line on where the agent is, as in the list: the summary's status, or
// its first line. Tapping it shows the whole recap, its age, and regenerating it.
const summary = computed(() => props.session.summary ?? null);
const goal = computed(() => summary.value?.status?.trim() || (summary.value?.text.split('\n').find((line) => line.trim())?.trim() ?? ''));
const goalOpen = ref(false);
const canSummarize = computed(() => !props.session.parentId && !props.session.id.includes(':'));

function chip(key: string) {
  return { open: openChip.value === key, 'onUpdate:open': (open: boolean) => { if (open) openChip.value = key; else if (openChip.value === key) openChip.value = null; } };
}
watch(() => props.session.id, () => {
  openChip.value = null;
  goalOpen.value = false;
});

function counted(count: number, one: string, many: string): string {
  return `${count} ${count === 1 ? one : many}`;
}

// The list row this agent belongs to. Only list rows pin and snooze.
const tab = computed(() => familyTabOf(sidebar, { sessionId: props.session.id }));
const menuTab = computed(() => props.session.id === tab.value?.family.rootId ? tab.value : undefined);

// The rest of the agent's family: its other agents, and the servers they
// started, each paired with the preview link that names its port.
const family = computed(() => tab.value?.family ?? null);
const agents = computed(() => family.value?.options.filter((option) => option.session.id !== props.session.id).map((option) => option.session) ?? []);
const agentsLabel = computed(() => props.session.id === tab.value?.family.rootId
  ? counted(agents.value.length, 'subagent', 'subagents')
  : counted(agents.value.length, 'agent', 'agents'));
const servers = computed(() => familyServers(family.value ? sidebar.ownedProcesses(family.value) : [], links.value.filter((link) => link.resource_type === 'preview'), linkLabel));
const serversLabel = computed(() => servers.value.length === 1 ? servers.value[0]!.label : counted(servers.value.length, 'server', 'servers'));

function openAgent(session: SessionRecord): void {
  openChip.value = null;
  if (tab.value) sidebar.selectSession(tab.value.family.rootId, session);
}
function openProcess(process: ProcessRecord): void {
  openChip.value = null;
  sidebar.selectProcess(process);
}
function openServer(server: (typeof servers.value)[number]): void {
  openChip.value = null;
  if (server.url && hasBrowser(props.session.processId)) emit('peek', { kind: 'browser', url: server.url, serverProcessId: server.process?.id ?? null });
  else if (server.url) window.open(server.url, '_blank', 'noopener,noreferrer');
  else if (server.process) sidebar.selectProcess(server.process);
}
function openDiff(worktree: SessionWorktree): void {
  openChip.value = null;
  emit('peek', { kind: 'diff', worktree });
}
function openImage(index: number): void {
  openChip.value = null;
  emit('peek', { kind: 'image', images: gallery.value, index });
}

const todoDialogOpen = ref(false), noteDialogOpen = ref(false), draftTitle = ref('');
function createTodo(title: string): void {
  draftTitle.value = title;
  todoDialogOpen.value = true;
}
function createScratchpad(title: string): void {
  draftTitle.value = title;
  noteDialogOpen.value = true;
}
</script>
