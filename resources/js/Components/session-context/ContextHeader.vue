<template>
  <!-- The agent's context in the conversation: its name, the goal from its
       summary, then a chip for each kind of thing attached to it, in a fixed
       order so their places become familiar. Empty kinds don't show; + adds
       one. A chip opens its list, as a sheet on a phone. -->
  <!-- No rule below it: a conversation fades in under it instead. -->
  <header class="relative z-10 shrink-0 bg-background" :class="phoneLayout ? (folded ? '' : 'pb-2.5') : 'pb-3 pt-4'">
    <div class="mx-auto w-full" :class="phoneLayout ? '' : ['px-4', inner]">
      <div class="flex items-center gap-1" :class="phoneLayout ? 'h-12 pl-1 pr-1.5' : ''">
        <slot name="leading" />
        <SidebarItemMenu :session="session" :tab="menuTab">
          <h1 class="min-w-0 flex-1 select-none truncate font-medium [-webkit-touch-callout:none]" :class="phoneLayout ? 'text-[16px]' : 'text-[15.5px]'">
            {{ agentLabel(session) }}<HostBadge v-if="session.host && (sidebar.allAgents.value || phoneLayout || session.host !== sidebar.projectHost.value)" :host="session.host" class="ml-1.5" /><StatusLabelPill v-if="session.statusLabel" :label="session.statusLabel" class="ml-2 align-[1px]" />
          </h1>
        </SidebarItemMenu>
        <slot name="trailing" />
      </div>
      <div v-if="summary && goal && !folded && !phoneLayout" class="mt-1 text-[13.5px] leading-5 text-muted-foreground">
        <button type="button" class="group/goal flex max-w-full items-start gap-1 rounded-sm text-left transition-colors hover:text-foreground/85 focus-visible:outline-none focus-visible:ring-1 focus-visible:ring-ring" :aria-expanded="goalOpen" @click="goalOpen = !goalOpen">
          <span v-if="goalOpen" class="min-w-0 whitespace-pre-wrap break-words text-foreground/85">{{ summary.text }}</span>
          <span v-else class="min-w-0 truncate">{{ goal }}</span>
          <ChevronDown class="mt-[3px] h-3.5 w-3.5 shrink-0 opacity-50 transition-[transform,opacity] group-hover/goal:opacity-100" :class="goalOpen && 'rotate-180'" aria-hidden="true" />
        </button>
        <p v-if="goalOpen" class="mt-0.5 flex items-center gap-1.5 text-[11.5px]">
          <span :title="`Generated by ${summary.model} on ${new Date(summary.generatedAt).toLocaleString()}`">Updated {{ relativeTime(summary.generatedAt, now) }}</span>
          <AutoSummaryControls v-if="canSummarize" :key="session.id" :project-id="projectId" :session-id="session.id" class="-my-1" />
        </p>
      </div>
      <!-- Folding hides the chips without unmounting them, so an open chip's
           form survives the phone keyboard that typing in it brings up, and
           a new secret request still opens its list. -->
      <div v-show="!folded || openChip" class="flex items-center gap-1.5" :class="phoneLayout ? 'mt-1.5 overflow-x-auto px-3 [scrollbar-width:none]' : 'mt-2.5 flex-wrap'">
        <ResponsivePopover v-if="worktrees.length" v-bind="chip('worktrees')" title="Worktrees" content-class="w-[22rem]" :keep-focus="openingDiff">
          <template #trigger><button type="button" :class="CHIP" v-bind="trigger('worktrees')"><FolderGit2 :class="CHIP_ICON" /><span :class="CHIP_LABEL">{{ counted(worktrees.length, 'worktree', 'worktrees') }}</span><ChipUnpin v-if="isPinned('worktrees')" :title="PIN_META.worktrees.title" @unpin="emit('unpin', 'worktrees')" /></button></template>
          <ContextPinBar v-if="canPin" title="Worktrees" :tab-into="tabInto" @pin="pin('worktrees')" @tab="tab('worktrees')" />
          <ContextList kind="worktrees" :project-id="projectId" :session="session" :active-worktree-id="activeWorktreeId" @open-worktree="openDiff" @done="openChip = null" />
        </ResponsivePopover>

        <ResponsivePopover v-if="pages.length" v-bind="chip('links')" title="Links">
          <template #trigger><button type="button" :class="CHIP" v-bind="trigger('links')"><component :is="pages.length === 1 ? linkIcon(pages[0]!) : Link2" :class="CHIP_ICON" /><span :class="[CHIP_LABEL, 'max-w-48 truncate']">{{ pages.length === 1 ? linkLabel(pages[0]!) : `${pages.length} links` }}</span><ChipUnpin v-if="isPinned('links')" :title="PIN_META.links.title" @unpin="emit('unpin', 'links')" /></button></template>
          <ContextPinBar v-if="canPin" title="Links" :tab-into="tabInto" @pin="pin('links')" @tab="tab('links')" />
          <ContextList kind="links" :project-id="projectId" :session="session" @done="openChip = null" />
        </ResponsivePopover>

        <!-- The agent's own browser, once it has one. It opens beside the
             conversation. -->
        <button v-if="browser?.running" type="button" :class="CHIP" v-bind="trigger('browser')" @click="openBrowser"><Globe :class="CHIP_ICON" /><span :class="CHIP_LABEL">Browser</span><span v-if="browser.help" class="h-1.5 w-1.5 rounded-full bg-foreground" aria-label="needs you" /><ChipUnpin v-if="isPinned('browser')" :title="PIN_META.browser.title" @unpin="emit('unpin', 'browser')" /></button>

        <!-- Secrets the agent asked for or was given. A new request opens the
             list, where its form waits. They stay on the agent's own host. -->
        <SecretsChip v-if="hasSecrets(session.processId)" v-bind="chip('secrets')" :process-id="session.processId" :trigger="trigger('secrets')" :pinned="isPinned('secrets')" @unpin="emit('unpin', 'secrets')">
          <template #bar><ContextPinBar v-if="canPin" title="Secrets" :tab-into="tabInto" @pin="pin('secrets')" @tab="tab('secrets')" /></template>
        </SecretsChip>

        <!-- Servers the agent started, and preview links. One with a page opens
             it in the agent's browser beside the conversation. -->
        <ResponsivePopover v-if="servers.length" v-bind="chip('servers')" :title="serversLabel">
          <template #trigger><button type="button" :class="CHIP" v-bind="trigger('servers')"><MonitorPlay :class="CHIP_ICON" /><span :class="[CHIP_LABEL, 'max-w-48 truncate']">{{ serversLabel }}</span><ChipUnpin v-if="isPinned('servers')" :title="PIN_META.servers.title" @unpin="emit('unpin', 'servers')" /></button></template>
          <ContextPinBar v-if="canPin" title="Servers" :tab-into="tabInto" @pin="pin('servers')" @tab="tab('servers')" />
          <ContextList kind="servers" :project-id="projectId" :session="session" @peek="emit('peek', $event)" @done="openChip = null" />
        </ResponsivePopover>

        <!-- The rest of the agent's family, whether or not the sidebar lists them. -->
        <ResponsivePopover v-if="agents.length" v-bind="chip('agents')" :title="agentsLabel">
          <template #trigger><button type="button" :class="CHIP" v-bind="trigger('agents')"><Network :class="CHIP_ICON" /><span :class="CHIP_LABEL">{{ agentsLabel }}</span><ChipUnpin v-if="isPinned('agents')" :title="PIN_META.agents.title" @unpin="emit('unpin', 'agents')" /></button></template>
          <ContextPinBar v-if="canPin" title="Agents" :tab-into="tabInto" @pin="pin('agents')" @tab="tab('agents')" />
          <ContextList kind="agents" :project-id="projectId" :session="session" @done="openChip = null" />
        </ResponsivePopover>

        <ResponsivePopover v-if="openTodos" v-bind="chip('todos')" title="Todos" content-class="w-[22rem]">
          <template #trigger><button type="button" :class="CHIP" v-bind="trigger('todos')"><ListTodo :class="CHIP_ICON" /><span :class="CHIP_LABEL">{{ counted(openTodos, 'todo', 'todos') }}</span><ChipUnpin v-if="isPinned('todos')" :title="PIN_META.todos.title" @unpin="emit('unpin', 'todos')" /></button></template>
          <ContextPinBar v-if="canPin" title="Todos" :tab-into="tabInto" @pin="pin('todos')" @tab="tab('todos')" />
          <ContextList kind="todos" :project-id="projectId" :session="session" @done="openChip = null" />
        </ResponsivePopover>

        <ResponsivePopover v-if="scratchpads.length" v-bind="chip('scratchpads')" title="Scratchpads">
          <template #trigger><button type="button" :class="CHIP" v-bind="trigger('scratchpads')"><NotebookPen :class="CHIP_ICON" /><span :class="CHIP_LABEL">{{ counted(scratchpads.length, 'scratchpad', 'scratchpads') }}</span><ChipUnpin v-if="isPinned('scratchpads')" :title="PIN_META.scratchpads.title" @unpin="emit('unpin', 'scratchpads')" /></button></template>
          <ContextPinBar v-if="canPin" title="Scratchpads" :tab-into="tabInto" @pin="pin('scratchpads')" @tab="tab('scratchpads')" />
          <ContextList kind="scratchpads" :project-id="projectId" :session="session" @done="openChip = null" />
        </ResponsivePopover>

        <ResponsivePopover v-if="mediaTotal" v-bind="chip('media')" title="Media" content-class="w-72">
          <template #trigger><button type="button" :class="CHIP" v-bind="trigger('media')" :aria-label="counted(mediaTotal, 'image', 'images')"><Images :class="CHIP_ICON" />{{ mediaTotal }}<ChipUnpin v-if="isPinned('media')" :title="PIN_META.media.title" @unpin="emit('unpin', 'media')" /></button></template>
          <ContextPinBar v-if="canPin" title="Media" :tab-into="tabInto" @pin="pin('media')" @tab="tab('media')" />
          <ContextList kind="media" :project-id="projectId" :session="session" @peek="emit('peek', $event)" @done="openChip = null" />
        </ResponsivePopover>

        <ResponsivePopover v-bind="chip('add')" title="Add to this agent" content-class="w-56">
          <template #trigger>
            <button type="button" :class="ADD_CHIP" aria-label="Add a worktree, todo, scratchpad or link" title="Add a worktree, todo, scratchpad or link"><Plus class="h-4 w-4" /></button>
          </template>
          <ContextPicker :items="worktreeOptions" placeholder="Search worktrees…" label="Search worktrees to link" empty-text="This project has no worktrees." align="start" :disabled="busy || linkedWorktrees >= MAX_LINKED_WORKTREES" @select="linkWorktree">
            <button type="button" :class="ROW"><FolderGit2 :class="CHIP_ICON" />Worktree</button>
          </ContextPicker>
          <ContextPicker v-model:open="todoPickerOpen" v-model:query="todoQuery" :items="todoOptions" placeholder="Search or create a todo…" label="Search todos to assign" :empty-text="todoPickerLoaded ? 'No todos found.' : 'Loading…'" create-label="New todo" align="start" :disabled="busy" @select="assignTodo" @create="createTodo">
            <button type="button" :class="ROW"><ListTodo :class="CHIP_ICON" />Todo</button>
          </ContextPicker>
          <ContextPicker v-model:open="notePickerOpen" v-model:query="noteQuery" :items="noteOptions" placeholder="Search or create a scratchpad…" label="Search scratchpads to attach" :empty-text="notePickerLoaded ? 'No scratchpads found.' : 'Loading…'" create-label="New scratchpad" align="start" :disabled="busy" @select="attachScratchpad" @create="createScratchpad">
            <button type="button" :class="ROW"><NotebookPen :class="CHIP_ICON" />Scratchpad</button>
          </ContextPicker>
          <LinkAttachPopover :busy="busy" align="start" @attach="(url, done) => attachLink(url).then(done)">
            <button type="button" :class="ROW"><Link2 :class="CHIP_ICON" />Link</button>
          </LinkAttachPopover>
        </ResponsivePopover>
      </div>
      <p v-if="error" role="alert" class="mt-2 text-xs text-destructive" :class="phoneLayout && 'px-3'">{{ error }}</p>
    </div>
    <CreateContextItemDialog v-model:open="todoDialogOpen" kind="todo" :project-id="projectId" :session-id="session.id" :initial-title="draftTitle" @created="refresh" />
    <CreateContextItemDialog v-model:open="noteDialogOpen" kind="scratchpad" :project-id="projectId" :session-id="session.id" :initial-title="draftTitle" @created="refresh" />
  </header>
</template>

<script setup lang="ts">
import { computed, ref, watch } from 'vue';
import { cn } from '@/lib/utils';
import { ChevronDown, FolderGit2, Globe, Images, Link2, ListTodo, MonitorPlay, Network, NotebookPen, Plus } from 'lucide-vue-next';
import AutoSummaryControls from '../AutoSummaryControls.vue';
import CreateContextItemDialog from '../CreateContextItemDialog.vue';
import HostBadge from '../HostBadge.vue';
import ResponsivePopover from '../ResponsivePopover.vue';
import SidebarItemMenu from '../Sidebar/SidebarItemMenu.vue';
import StatusLabelPill from '../StatusLabelPill.vue';
import ChipUnpin from './ChipUnpin.vue';
import ContextList from './ContextList.vue';
import ContextPicker from './ContextPicker.vue';
import ContextPinBar from './ContextPinBar.vue';
import LinkAttachPopover from './LinkAttachPopover.vue';
import { CHIP, CHIP_ICON, CHIP_LABEL } from './rowAction';
import SecretsChip from './SecretsChip.vue';
import { counted, useAgentFamily } from '../../Composables/useAgentFamily';
import { useMedia } from '../../Composables/useMedia';
import { linkIcon, linkLabel, MAX_LINKED_WORKTREES, useSessionContext } from '../../Composables/useSessionContext';
import { agentLabel } from '../../lib/agentTabs';
import { useBrowserState } from '../../lib/browser';
import { relativeTime } from '../../lib/format';
import type { Peek } from '../../lib/peek';
import { phoneLayout } from '../../lib/phoneLayout';
import type { SessionWorktree } from '../../lib/projectContext';
import { hasSecrets } from '../../lib/secrets';
import type { PinKind } from '../../lib/tiling';
import { PIN_META } from '../tiling/pinMeta';
import type { SessionRecord } from '../../types';

// `inner` lines the header up with what's below it, such as the conversation
// column. Folded, only the name shows, as over a terminal while typing.
// With `canPin`, a chip's list can be pinned beside the conversation, as a
// tile of its own or a tab of `tabInto`. A pinned chip points at its tile
// rather than opening, and dragging a chip pins it where it's dropped.
const props = defineProps<{
  projectId: string; session: SessionRecord; inner?: string | undefined; activeWorktreeId?: string | null | undefined; folded?: boolean | undefined;
  canPin?: boolean | undefined; pinned?: readonly PinKind[] | undefined; tabInto?: string | null | undefined;
}>();
const emit = defineEmits<{ peek: [peek: Peek]; openWorktree: [worktree: SessionWorktree]; pin: [kind: PinKind]; tab: [kind: PinKind]; locate: [kind: PinKind]; unpin: [kind: PinKind]; grab: [kind: PinKind, event: PointerEvent] }>();

const ADD_CHIP = cn(CHIP, 'w-7 justify-center px-0 max-sm:w-8 max-sm:px-0');
const ROW = 'flex min-h-8 w-full min-w-0 flex-1 items-center gap-2.5 rounded-md px-2 py-1 text-left text-[13px] outline-none transition-colors hover:bg-muted/40 focus-visible:ring-1 focus-visible:ring-ring max-sm:min-h-11 max-sm:text-sm';
const PINNED = 'bg-white/[0.1] text-foreground';

// One chip's list open at a time.
const openChip = ref<string | null>(null);
const sessionProps = { get projectId() { return props.projectId; }, get sessionId() { return props.session.id; } };
const { now, todos, scratchpads, links, worktrees, linkedWorktrees, worktreeOptions, todoOptions, noteOptions, todoQuery, noteQuery, todoPickerOpen, notePickerOpen, todoPickerLoaded, notePickerLoaded, error, busy, refresh,
  linkWorktree, assignTodo, attachScratchpad, attachLink } = useSessionContext(sessionProps, { diffTotals: computed(() => false) });
const pages = computed(() => links.value.filter((link) => link.resource_type !== 'preview'));
const openTodos = computed(() => todos.value.filter((todo) => todo.status !== 'completed').length);
const browser = useBrowserState(() => props.session.processId);
const { sidebar, menuTab, agents, agentsLabel, servers, serversLabel } = useAgentFamily(() => props.session, () => links.value.filter((link) => link.resource_type === 'preview'));

// A paired host's media stays on that host.
const media = useMedia(sessionProps, { pageSize: 8, enabled: () => !props.session.id.includes(':') });
const mediaTotal = media.total;

// One line on where the agent is, as in the list: the summary's status, or
// its first line. Tapping it shows the whole recap, its age, and regenerating it.
const summary = computed(() => props.session.summary ?? null);
const goal = computed(() => summary.value?.status?.trim() || (summary.value?.text.split('\n').find((line) => line.trim())?.trim() ?? ''));
const goalOpen = ref(false);
const canSummarize = computed(() => !props.session.parentId && !props.session.id.includes(':'));

function isPinned(kind: PinKind): boolean {
  return Boolean(props.canPin && props.pinned?.includes(kind));
}
function chip(key: string) {
  return { open: openChip.value === key, 'onUpdate:open': (open: boolean) => {
    if (open && isPinned(key as PinKind)) { emit('locate', key as PinKind); return; }
    if (open) { openChip.value = key; openingDiff.value = false; }
    else if (openChip.value === key) openChip.value = null;
  } };
}
// A chip's trigger shows when it's pinned, and hands its pointer on so it
// can be dragged beside the conversation.
function trigger(kind: PinKind): Record<string, unknown> {
  if (!props.canPin) return {};
  return {
    class: isPinned(kind) ? PINNED : undefined,
    title: isPinned(kind) ? 'Pinned beside the conversation. Show it' : undefined,
    onPointerdown: (event: PointerEvent) => { if (event.button === 0 && !event.altKey) emit('grab', kind, event); }
  };
}
function pin(kind: PinKind): void {
  openChip.value = null;
  emit('pin', kind);
}
function tab(kind: PinKind): void {
  openChip.value = null;
  emit('tab', kind);
}
function openBrowser(): void {
  if (isPinned('browser')) emit('locate', 'browser');
  else emit('peek', { kind: 'browser' });
}
watch(() => props.session.id, () => {
  openChip.value = null;
  goalOpen.value = false;
});

// The diff takes focus as it opens, so the closing popover leaves focus alone
// rather than handing it back to its chip under the diff.
const openingDiff = ref(false);
function openDiff(worktree: SessionWorktree): void {
  openingDiff.value = true;
  openChip.value = null;
  emit('openWorktree', worktree);
}

const todoDialogOpen = ref(false), noteDialogOpen = ref(false), draftTitle = ref('');
function createTodo(title: string): void {
  draftTitle.value = title;
  todoDialogOpen.value = true;
}
function createScratchpad(title: string): void {
  draftTitle.value = title;
  noteDialogOpen.value = true;
}
</script>
