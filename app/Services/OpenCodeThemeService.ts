import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { isDeepStrictEqual } from 'node:util';
import { applyEdits, modify, parse, type ParseError } from 'jsonc-parser';
import { openCodeTheme } from '../Harness/OpenCodeTheme';
import { LinkedEntries } from '../Platform/LinkedEntries';
import { samePath } from '../Platform/Paths';

// Keep native CLI saves in a persistent Patterm config directory. Other config
// files remain linked to the user config for credentials and relative plugins.
// OpenCode keeps this directory at ~/.config/opencode on Windows too (it reads
// xdg-basedir, which ignores %APPDATA%), so the default source is the same.
// Windows links with junctions and hard links; see LinkedEntries.
export function prepareOpenCodeTheme(runtimeDir: string, env: NodeJS.ProcessEnv = process.env): string {
  const source = path.resolve(env.OPENCODE_CONFIG_DIR || path.join(env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config'), 'opencode'));
  const target = path.resolve(runtimeDir, 'opencode-config');
  if (samePath(source, target)) throw new Error('OpenCode theme config must be separate from the user config');
  const configPath = path.join(target, 'cli.json');
  const themePath = path.join(target, 'themes', 'patterm-opencode.json');
  const baselinePath = path.join(target, '.patterm-source.json');
  const upstream = readConfig(path.join(source, 'cli.json'));
  const upstreamTheme = (upstream.config.theme as { name?: string } | undefined)?.name;
  if (!upstreamTheme || upstreamTheme === 'opencode') {
    upstream.text = applyEdits(upstream.text, modify(upstream.text, ['theme', 'name'], 'patterm-opencode', {}));
    upstream.config = parse(upstream.text);
  }
  const saved = readConfig(configPath, upstream.text);
  let text = saved.text;
  // Migrate the old forced system theme, leaving later native theme selections alone.
  if (!fs.existsSync(themePath) && (saved.config.theme as { name?: string } | undefined)?.name === 'system') {
    text = applyEdits(text, modify(text, ['theme', 'name'], 'patterm-opencode', {}));
    saved.config = parse(text);
  }
  const previous = readConfig(baselinePath).config;
  const merged = mergeConfig(previous, upstream.config, saved.config) as Record<string, unknown>;
  text = updateConfigText(text, saved.config, merged);
  fs.mkdirSync(target, { recursive: true, mode: 0o700 });
  let entries: string[] = [];
  try { entries = fs.readdirSync(source); }
  catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
  const manifest = path.join(target, '.patterm-links.json');
  // Remove stale links without touching files generated by the native CLI.
  const linked = new LinkedEntries(target, manifest, 'config');
  linked.removeStale(entries);
  for (const entry of entries) {
    if (entry === 'cli.json' || entry === 'themes' || entry === '.patterm-source.json' || entry === '.patterm-links.json') continue;
    linked.link(path.join(source, entry), entry, true);
  }
  const themesDir = path.dirname(themePath);
  // Older launches linked the whole directory. Replace only that link.
  if (fs.lstatSync(themesDir, { throwIfNoEntry: false })?.isSymbolicLink()) fs.unlinkSync(themesDir);
  fs.mkdirSync(themesDir, { recursive: true, mode: 0o700 });
  let themes: string[] = [];
  try { themes = fs.readdirSync(path.join(source, 'themes')); }
  catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
  const linkedThemes = new LinkedEntries(themesDir, manifest, 'themes');
  linkedThemes.removeStale(themes);
  for (const theme of themes) {
    if (theme !== 'patterm-opencode.json') linkedThemes.link(path.join(source, 'themes', theme), theme, false);
  }
  if (text !== saved.text || !fs.existsSync(configPath)) writeConfig(configPath, text);
  if (!isDeepStrictEqual(previous, upstream.config)) writeConfig(baselinePath, JSON.stringify(upstream.config));
  // The theme file is generated from the bundled palette. Refresh it when that
  // palette changes, but leave a matching file alone.
  let installedTheme: unknown;
  try { installedTheme = JSON.parse(fs.readFileSync(themePath, 'utf8')); }
  catch { installedTheme = undefined; }
  if (!isDeepStrictEqual(installedTheme, openCodeTheme)) writeConfig(themePath, JSON.stringify(openCodeTheme));
  return target;
}

function readConfig(filename: string, fallback = '{}'): { text: string; config: Record<string, unknown> } {
  let text = fallback;
  try { text = fs.readFileSync(filename, 'utf8'); }
  catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
  const errors: ParseError[] = [];
  const config: unknown = parse(text, errors, { allowTrailingComma: true });
  if (errors.length || !isObject(config)) throw new Error(`OpenCode config ${filename} is not a valid JSONC object`);
  return { text, config };
}

function isObject(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

// Arrays are single settings. Local changes win conflicts, including deletions.
function mergeConfig(previous: unknown, upstream: unknown, saved: unknown): unknown {
  if (isDeepStrictEqual(saved, previous)) return upstream;
  if (isObject(saved) && (isObject(previous) || previous === undefined) && (isObject(upstream) || upstream === undefined)) {
    const before = previous ?? {};
    const next = upstream ?? {};
    return Object.fromEntries([...new Set([...Object.keys(before), ...Object.keys(next), ...Object.keys(saved)])]
      .map((key) => [key, mergeConfig(before[key], next[key], saved[key])] as const)
      .filter(([, value]) => value !== undefined));
  }
  return saved;
}

// Apply only changed leaves so native JSONC comments and formatting survive.
function updateConfigText(text: string, before: unknown, after: unknown, keys: string[] = []): string {
  if (isDeepStrictEqual(before, after)) return text;
  if (isObject(before) && isObject(after)) {
    for (const key of new Set([...Object.keys(before), ...Object.keys(after)])) {
      text = updateConfigText(text, before[key], after[key], [...keys, key]);
    }
    return text;
  }
  return applyEdits(text, modify(text, keys, after, {}));
}

function writeConfig(filename: string, text: string): void {
  const temporary = `${filename}.${randomUUID()}.tmp`;
  try {
    fs.writeFileSync(temporary, text, { mode: 0o600, flag: 'wx' });
    fs.renameSync(temporary, filename);
  } finally {
    fs.rmSync(temporary, { force: true });
  }
}
